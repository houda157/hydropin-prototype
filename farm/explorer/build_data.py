"""Pack the farm map and the leak dataset into farm/explorer/farm-data.js for the explorer page.

    python -m farm.explorer.build_data

Run it again after `python -m farm.leaks.generate` (e.g. with Role 1's measured sigma) so the
page shows the current data. The page loads the file as a script, so it opens straight from
disk (double-click index.html) without a web server.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
FARM = HERE.parent
OUT_DIR = FARM / "leaks" / "out"


def build() -> dict:
    lay = json.loads((FARM / "model" / "layout.json").read_text(encoding="utf-8"))
    meta = json.loads((OUT_DIR / "meta.json").read_text(encoding="utf-8"))
    sc = pd.read_csv(OUT_DIR / "scenarios.csv")
    dP = np.load(OUT_DIR / "dP_all.npy")                     # [scenarios x 28] bar
    assert dP.shape == (len(sc), len(meta["node_order"]))
    return {
        "simulation": True,
        "sigma_bar": meta["sigma_bar"],
        "units": "dP in 0.1 mbar (integers), negative = pressure drop",
        "farm": lay["farm"],
        "nodes": [{k: n[k] for k in ("id", "x", "y", "kind", "sector", "branch", "candidate")} for n in lay["nodes"]],
        "pipes": [{"id": p["id"], "from": p["from"], "to": p["to"], "kind": p["kind"], "sector": p["sector"],
                   "branch": p["branch"], "d": p.get("diameter"), "leak": p["leak_candidate"]} for p in lay["pipes"]],
        "sectors": [{"id": s["id"], "bbox": s["bbox"], "side": s["side"], "row": s["row"]} for s in lay["sectors"]],
        "node_order": meta["node_order"],
        "candidate_order": meta["candidate_order"],
        "configs": {i: cfg for i, cfg in enumerate(lay["farm"]["irrigation_shifts"])},
        "scen": {
            "at": sc.leak_at.tolist(), "kind": sc.leak_kind.tolist(), "branch": sc.branch.tolist(),
            "size": sc.size_pct.astype(int).tolist(), "cfg": sc.config_id.tolist(),
            "world": (sc.world_id % 10).tolist(),            # farm version 0-9 within each shift
            "x": sc.x.round(1).tolist(), "y": sc.y.round(1).tolist(),
            "leak": sc.leak_lps.round(2).tolist(), "pump": sc.pump_lps.round(2).tolist(),
            "pump0": sc.healthy_pump_lps.round(2).tolist(),
        },
        "dP": np.round(dP * 10000).astype(int).ravel().tolist(),   # bar -> 0.1 mbar
    }


def main() -> None:
    data = build()
    out = HERE / "farm-data.js"
    out.write_text("// Generated by farm/explorer/build_data.py from farm/leaks/out - do not edit.\n"
                   "window.FARM_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"{len(data['scen']['at'])} scenarios -> {out.relative_to(FARM.parent)} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
